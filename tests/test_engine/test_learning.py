class TestAdaptationRegistry:
    def _make_candidate(self, **kwargs: object) -> AdaptationCandidate:
        defaults = dict(source="prompt_opt", confidence=0.8, sample_size=10)
        defaults.update(kwargs)
        return AdaptationCandidate(**defaults)  # type: ignore[arg-type]

    def test_add_and_list(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        assert reg.count() == 1
        assert len(reg.list_pending()) == 1
        assert len(reg.list_applied()) == 0

    def test_approve(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.approve(c.id)
        assert reg.get(c.id) is not None
        assert reg.get(c.id).status == "applied"
        assert reg.get(c.id).applied_at is not None
        assert len(reg.list_pending()) == 0
        assert len(reg.list_applied()) == 1

    def test_approve_not_found(self) -> None:
        reg = AdaptationRegistry()
        with pytest.raises(KeyError):
            reg.approve("nonexistent")

    def test_approve_wrong_state(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.approve(c.id)
        with pytest.raises(ValueError, match="Cannot approve"):
            reg.approve(c.id)

    def test_reject(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.reject(c.id)
        assert reg.get(c.id).status == "rejected"

    def test_reject_not_found(self) -> None:
        reg = AdaptationRegistry()
        with pytest.raises(KeyError):
            reg.reject("nonexistent")

    def test_reject_wrong_state(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.reject(c.id)
        with pytest.raises(ValueError, match="Cannot reject"):
            reg.reject(c.id)

    def test_rollback(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.approve(c.id)
        reg.rollback(c.id, "quality dropped")
        assert reg.get(c.id).status == "rolled_back"
        assert reg.get(c.id).last_outcome == "quality dropped"

    def test_rollback_not_applied(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        with pytest.raises(ValueError, match="Cannot rollback"):
            reg.rollback(c.id, "reason")

    def test_regression_detected(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.approve(c.id)
        detected = reg.check_regression(c.id, recent_quality=0.6, baseline_quality=0.9)
        assert detected is True
        assert reg.get(c.id).status == "rolled_back"

    def test_no_regression(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.approve(c.id)
        detected = reg.check_regression(c.id, recent_quality=0.85, baseline_quality=0.9)
        assert detected is False
        assert reg.get(c.id).status == "applied"

    def test_regression_zero_baseline(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.approve(c.id)
        assert reg.check_regression(c.id, recent_quality=0.5, baseline_quality=0.0) is False

    def test_regression_custom_threshold(self) -> None:
        reg = AdaptationRegistry()
        c = self._make_candidate()
        reg.add(c)
        reg.approve(c.id)
        detected = reg.check_regression(
            c.id, recent_quality=0.8, baseline_quality=0.9, threshold=0.05,
        )
        assert detected is True

    def test_regression_not_found(self) -> None:
        reg = AdaptationRegistry()
        with pytest.raises(KeyError):
            reg.check_regression("nope", 0.5, 0.9)


