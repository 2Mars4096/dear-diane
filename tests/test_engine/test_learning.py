class TestJsonFileBackend:
    def test_load_empty(self, tmp_path: Path) -> None:
        backend = JsonFileBackend(tmp_path / "mem.json")
        assert backend.load() == {}

    def test_save_and_load(self, tmp_path: Path) -> None:
        backend = JsonFileBackend(tmp_path / "mem.json")
        backend.save({"item1": {"content": "hello", "memory_type": "fact"}})
        loaded = backend.load()
        assert "item1" in loaded
        assert loaded["item1"]["content"] == "hello"

    def test_upsert(self, tmp_path: Path) -> None:
        backend = JsonFileBackend(tmp_path / "mem.json")
        backend.upsert("id1", {"content": "first"})
        backend.upsert("id2", {"content": "second"})
        loaded = backend.load()
        assert len(loaded) == 2
        backend.upsert("id1", {"content": "updated"})
        loaded = backend.load()
        assert loaded["id1"]["content"] == "updated"

    def test_delete(self, tmp_path: Path) -> None:
        backend = JsonFileBackend(tmp_path / "mem.json")
        backend.upsert("id1", {"content": "hello"})
        backend.delete("id1")
        assert backend.load() == {}

    def test_delete_nonexistent(self, tmp_path: Path) -> None:
        backend = JsonFileBackend(tmp_path / "mem.json")
        backend.delete("nonexistent")

    def test_query_by_type(self, tmp_path: Path) -> None:
        backend = JsonFileBackend(tmp_path / "mem.json")
        backend.save({
            "a": {"memory_type": "fact", "content": "x"},
            "b": {"memory_type": "preference", "content": "y"},
            "c": {"memory_type": "fact", "content": "z"},
        })
        results = backend.query(memory_type="fact")
        assert len(results) == 2

    def test_query_no_match(self, tmp_path: Path) -> None:
        backend = JsonFileBackend(tmp_path / "mem.json")
        backend.save({"a": {"memory_type": "fact"}})
        results = backend.query(memory_type="principle")
        assert len(results) == 0

    def test_corrupted_file(self, tmp_path: Path) -> None:
        path = tmp_path / "mem.json"
        path.write_text("not json", encoding="utf-8")
        backend = JsonFileBackend(path)
        assert backend.load() == {}


